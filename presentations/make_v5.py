# -*- coding: utf-8 -*-
"""v4 -> v5: слайд «Гипотезы» переписан под тройку создателя.

Было: частота / истина / алайнмент (алайнмент дублируется слайдами «Как вообще
учат модель» и «Слой 1/2»). Стало: данных больше / правда короче / правду проще
сжать — тройка ложится ровно на контроли эксперимента (частота 50/50,
length-matched, learnable), а третья карточка несёт главный тезис: цель модели —
не истина, а точка зрения, которая лучше всего объясняет наблюдаемый мир.

Иконки карточек (✕ ✕ ≈) не трогаем: первые две гипотезы снимаются, третья —
главный подозреваемый. v4 не перезаписывается.
"""
from pptx import Presentation

SRC = "/Users/krestnikov/giga/compression-drives-truth/presentations/gigarnd_compression_truth_v4.pptx"
OUT = "/Users/krestnikov/giga/compression-drives-truth/presentations/gigarnd_compression_truth_v5.pptx"

prs = Presentation(SRC)

hyp = next(s for s in prs.slides if any(
    sh.has_text_frame and sh.text_frame.text == "Три «очевидных» объяснения — и почему их мало"
    for sh in s.shapes))

MAP = {
    "Три «очевидных» объяснения — и почему их мало":
        "Три подозреваемых: частота, длина, сжимаемость",
    # карточка 1: частота
    "Частота": "Данных больше",
    "Чаще встречается → в это и верит.":
        "Правильного в вебе просто больше — модель верит большинству.",
    "Не работает: астрологии много, но её отвергают. И наш эксперимент "
    "держит частоту 50/50.":
        "Парадокс выше это уже убил: астрологии море, а модели её отвергают. "
        "В эксперименте частота будет ровно 50/50.",
    # карточка 2: длина
    "Истина": "Правда короче",
    "Объектив «знает» правду.":
        "Верные тексты компактнее, а вероятность любит короткое.",
    "Не работает: при равной частоте объектив НЕ отличает согласованную "
    "ложь от правды.":
        "Коварная гипотеза: длину придётся жёстко уравнивать. Дважды чуть "
        "не обманула меня самого — увидите.",
    # карточка 3: сжимаемость
    "Алайнмент": "Правда логична",
    "RLHF и политика прививают скепсис.":
        "У правды внутренняя логика: вся система описывается кратко.",
    "Часть ответа — но расхождение видно и в БАЗЕ, до алайнмента. Значит, "
    "есть слой глубже.":
        "Главный подозреваемый: модель — почти идеальный архиватор. "
        "Тогда её цель — не истина, а лучшее объяснение наблюдаемого "
        "мира.",
    # нижняя строка: мостик к «Как вообще учат модель»
    "Разберём глубокий слой на чистом эксперименте, где частота, формат и "
    "домен зафиксированы.":
        "Но сначала выясним, чей голос мы вообще слышим в ответах — самой "
        "модели или её воспитания.",
}

hit = set()
for sh in hyp.shapes:
    if not sh.has_text_frame:
        continue
    for para in sh.text_frame.paragraphs:
        for run in para.runs:
            if run.text in MAP:
                hit.add(run.text)
                run.text = MAP[run.text]
missed = set(MAP) - hit
if missed:
    raise SystemExit(f"НЕ НАЙДЕНЫ строки: {missed}")

prs.save(OUT)
print(f"saved {OUT} | slides: {len(prs.slides._sldIdLst)}")
